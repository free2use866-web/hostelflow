import { authTables } from "@convex-dev/auth/server";
import { defineSchema, defineTable } from "convex/server";
import { Infer, v } from "convex/values";

// default user roles. can add / remove based on the project as needed
export const ROLES = {
  ADMIN: "admin",
  USER: "user",
  MEMBER: "member",
} as const;

export const roleValidator = v.union(
  v.literal(ROLES.ADMIN),
  v.literal(ROLES.USER),
  v.literal(ROLES.MEMBER),
);
export type Role = Infer<typeof roleValidator>;

// ─── Hostel app roles ────────────────────────────────────────────────────────
export const HOSTEL_ROLES = {
  STUDENT: "student",
  MESS_SECY: "mess_secy",
  GENERAL_SECY: "general_secy",
  MAINTENANCE_SECY: "maintenance_secy",
  SUGGESTION_SECY: "suggestion_secy",
  ASSISTANT_WARDEN: "assistant_warden",
  CHIEF_WARDEN: "chief_warden",
  WARDEN: "warden",
} as const;

export const hostelRoleValidator = v.union(
  v.literal(HOSTEL_ROLES.STUDENT),
  v.literal(HOSTEL_ROLES.MESS_SECY),
  v.literal(HOSTEL_ROLES.GENERAL_SECY),
  v.literal(HOSTEL_ROLES.MAINTENANCE_SECY),
  v.literal(HOSTEL_ROLES.SUGGESTION_SECY),
  v.literal(HOSTEL_ROLES.ASSISTANT_WARDEN),
  v.literal(HOSTEL_ROLES.CHIEF_WARDEN),
  v.literal(HOSTEL_ROLES.WARDEN),
);
export type HostelRole = Infer<typeof hostelRoleValidator>;

export const CATEGORIES = ["mess", "general", "maintenance", "suggestion"] as const;
export const categoryValidator = v.union(...CATEGORIES.map((c) => v.literal(c)));
export type Category = Infer<typeof categoryValidator>;

export const TICKET_STATUSES = ["open", "in_progress", "resolved", "rejected"] as const;
export const statusValidator = v.union(...TICKET_STATUSES.map((s) => v.literal(s)));
export type TicketStatus = Infer<typeof statusValidator>;

export const MEALS = ["breakfast", "lunch", "snacks", "dinner"] as const;
export const mealValidator = v.union(...MEALS.map((m) => v.literal(m)));
export type Meal = Infer<typeof mealValidator>;

const schema = defineSchema(
  {
    // default auth tables using convex auth.
    ...authTables, // do not remove or modify

    // the users table is the default users table that is brought in by the authTables
    users: defineTable({
      name: v.optional(v.string()), // name of the user. do not remove
      image: v.optional(v.string()), // image of the user. do not remove
      email: v.optional(v.string()), // email of the user. do not remove
      emailVerificationTime: v.optional(v.number()), // email verification time. do not remove
      isAnonymous: v.optional(v.boolean()), // is the user anonymous. do not remove

      role: v.optional(roleValidator), // role of the user. do not remove

      // Hostel app fields
      hostelRole: v.optional(hostelRoleValidator),
      isDemo: v.optional(v.boolean()),
      rollNumber: v.optional(v.string()),
      roomNumber: v.optional(v.string()),
    }).index("email", ["email"]), // index for the email. do not remove or modify

    // Complaints / suggestions
    tickets: defineTable({
      title: v.string(),
      description: v.string(),
      category: categoryValidator,
      status: statusValidator,
      createdBy: v.id("users"),
      assignedTo: v.optional(v.id("users")), // secy currently handling it
      mentionedIds: v.array(v.id("users")), // people @mentioned → notified
      createdAt: v.number(),
      updatedAt: v.number(),
    })
      .index("by_category", ["category"])
      .index("by_creator", ["createdBy"])
      .index("by_status", ["status"])
      .index("by_assigned", ["assignedTo"]),

    // Timeline entries on a ticket: comments, transfers, status changes
    ticketUpdates: defineTable({
      ticketId: v.id("tickets"),
      authorId: v.optional(v.id("users")),
      type: v.union(
        v.literal("comment"),
        v.literal("created"),
        v.literal("transfer"),
        v.literal("status_change"),
      ),
      body: v.optional(v.string()),
      fromCategory: v.optional(categoryValidator),
      toCategory: v.optional(categoryValidator),
      fromStatus: v.optional(statusValidator),
      toStatus: v.optional(statusValidator),
      createdAt: v.number(),
    }).index("by_ticket", ["ticketId"]),

    // In-app notifications
    notifications: defineTable({
      userId: v.id("users"),
      ticketId: v.optional(v.id("tickets")),
      message: v.string(),
      read: v.boolean(),
      createdAt: v.number(),
    }).index("by_user", ["userId"]).index("by_user_read", ["userId", "read"]),

    // Mess tokens generated by students
    messTokens: defineTable({
      userId: v.id("users"),
      tokenCode: v.string(),
      meal: mealValidator,
      date: v.string(), // YYYY-MM-DD
      status: v.union(v.literal("active"), v.literal("used"), v.literal("cancelled")),
      createdAt: v.number(),
    })
      .index("by_user", ["userId"])
      .index("by_date", ["date"]),
  },
  {
    schemaValidation: false,
  },
);

export default schema;
